function shariaAttendance(court: 'general' | 'specialized'): LitigationDeadline {
  return {
    id: `sharia-44-attendance-${court}`,
    kind: 'attendance',
    title: court === 'general'
      ? 'موعد حضور المدعى عليه أمام المحكمة العامة'
      : 'موعد حضور المدعى عليه أمام المحاكم العمالية والتجارية والأحوال الشخصية',
    period: court === 'general' ? 'ثمانية أيام على الأقل' : 'أربعة أيام على الأقل',
    startsFrom: 'من تاريخ تبليغ صحيفة الدعوى',
    exceptions: SHARIA_ATTENDANCE_EXCEPTION,
    article: 'المادة (44)',
    source: SOURCES.shariaProcedure,
    officialText: SHARIA_ATTENDANCE_TEXT,
    levels: ['first'],
    status: 'verified',
  };
}

