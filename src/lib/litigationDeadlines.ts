export function deadlinesFor(systemId: CourtSystemId, levelId: CourtLevelId): LitigationDeadline[] {
  return (LITIGATION_DEADLINES[systemId] || []).filter((deadline) => deadline.levels.includes(levelId));
}

function formatDeadline(deadline: LitigationDeadline, index: number): string {
  return [
    `${index + 1}. ${DEADLINE_KIND_LABELS[deadline.kind]} — ${deadline.title}${deadline.status === 'verify' ? ' [يحتاج تحققاً]' : ''}`,
    `   المدة: ${deadline.period}`,
    `   تبدأ: ${deadline.startsFrom}`,
    deadline.scope ? `   النطاق: ${deadline.scope}` : '',
    deadline.consequence ? `   الأثر: ${deadline.consequence}` : '',
    deadline.exceptions ? `   الاستثناء: ${deadline.exceptions}` : '',
    `   السند: ${deadline.source.law} — ${deadline.article} — ${deadline.source.decree}`,
    deadline.note ? `   ملاحظة: ${deadline.note}` : '',
    `   النص الرسمي: «${deadline.officialText}»`,
  ].filter(Boolean).join('\n');
}

/**
 * كتلة المدد التي تضاف إلى حزمة المصادر: لكل مراحل جلسة المحكمة الافتراضية،
 * أو (forCourtroom = false) للمحادثة وأدوات المراجعة بلا أدوار المحكمة.
 */
export function buildDeadlinesInstruction(systemId: CourtSystemId, levelId: CourtLevelId, forCourtroom = true): string {
  const deadlines = deadlinesFor(systemId, levelId);
  if (!deadlines.length) return '';
  return [
    `[المدد النظامية لهذه المحكمة — منقولة من النص الرسمي في بوابة هيئة الخبراء، آخر مطابقة ${DEADLINES_VERIFIED_ON}]`,
    'هذه المدد خاصة بهذه الجهة القضائية وهذه الدرجة؛ لا تُنقل مدة جهة إلى جهة أخرى (مدد ديوان المظالم لا تطبق أمام المحاكم العامة أو التجارية، والعكس).',
    'احسبوا كل مدة من تواريخ ملف القضية فقط. إن غاب تاريخ لازم (نشوء الحق، العلم بالقرار، التظلم، انتهاء علاقة العمل، تسلم صك الحكم) فاذكروه ناقصاً ولا تفترضوه.',
    'لا يُقرر سقوط الحق أو عدم السماع أو عدم القبول إلا إذا ثبت من الملف انقضاء المدة وانتفاء الاستثناء (الإقرار أو العذر أو النص الخاص).',
    forCourtroom
      ? 'وكيل القاضي الأول يفحص كل مدة أدناه قبل الموضوع. المدعي العام يدفع بفوات المدة متى ثبت من الملف. وكيل المواد والأنظمة يثبت استيفاء المدة بسندها، ووكيل الثغرات ينبه إلى أي تاريخ ناقص.'
      : '',
    'المدة الموسومة [يحتاج تحققاً] لا يُبنى عليها دفع حاسم؛ تُذكر كمسألة يلزم التحقق منها.',
    ...deadlines.map(formatDeadline),
  ].filter(Boolean).join('\n');
}
