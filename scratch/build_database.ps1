### 📑 البنية الداخلية الموحدة لكل نظام (System Folder Standard)

يحتوي كل مجلد نظام على 5 مكونات قياسية:
1. **`01_نص_النظام.md`**: يضم ديباجة النظام ومواده مفهرسة حسب الأبواب والفصول.
2. **`02_اللائحة_التنفيذية.md`**: مواد اللائحة وقواعدها التفسيرية المرتبطة بكل مادة نظامية.
3. **`03_التعديلات_والقرارات.md`**: تاريخ التعديلات، المراسيم الملكية اللاحقة، وقرارات مجلس الوزراء.
4. **`04_السوابق_والمبادئ_القضائية.md`**: المبادئ القضائية المستقرة الصادرة من المحكمة العليا، محاكم الاستئناف، أو ديوان المظالم.
5. **`metadata.json`**: بطاقة التعريف الرقمية للنظام المستخدمة للربط البرمجي ومحركات البحث.

---

### 🔍 حقول البيانات الوصفية (Metadata Schema)
يحتوي ملف `metadata.json` لكل نظام على البيانات التالية:
- `id`: المعرف الفريد للنظام (Slug).
- `name_ar`: اسم النظام باللغة العربية.
- `name_en`: اسم النظام باللغة الإنجليزية.
- `category`: التصنيف الرئيسي (إدارية / عامة / جزائية).
- `sub_category`: التصنيف الفرعي.
- `royal_decree`: رقم وتاريخ المرسوم الملكي التأسيسي.
- `issue_date_hijri`: تاريخ الصدور بالهجري.
- `status`: حالة النظام (ساري / معدل / ملغى).
- `supervising_authority`: الجهة القضائية أو الحكومية المشرفة.
- `tags`: وسوم البحث والتصنيف لمنصة أصول القضاء.

---
